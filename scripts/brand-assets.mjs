/*
 * Regenerates the site's brand images from the committed brand sources.
 *
 *   node scripts/brand-assets.mjs
 *
 * Sources (see assets/brand/README.md):
 *   src/components/brand/symbol.json   the symbol's geometry, also drawn inline by the header and footer
 *   assets/brand/tsr-logo-horizontal.svg  the horizontal logo, wordmark outlined
 *   assets/brand/fonts/IBMPlexSans-Regular.ttf  for the social card's tagline (outlined, so no font is needed to view it)
 *
 * Writes:
 *   public/favicon.svg              the small-size symbol; follows the browser's dark mode
 *   public/favicon.ico              16, 32 and 48 px PNG images, light colours
 *   public/apple-touch-icon.png     180 px, on white (iOS adds its own rounded mask)
 *   public/images/brand/tsr-logo.png   512 px square, on white: the Organization logo in structured data
 *   public/share/social-card.png    1200 × 630, the link-preview image of every page
 *
 * Not run by the build: the outputs are committed, so what is published is
 * exactly what was reviewed. The tagline is read from src/content/site.json;
 * rerun this after changing it.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import sharp from 'sharp'
import opentype from 'opentype.js'

const ROOT = process.cwd()
const read = (path) => readFile(resolve(ROOT, path))
const symbol = JSON.parse(await read('src/components/brand/symbol.json'))
const site = JSON.parse(await read('src/content/site.json'))
const { light, dark } = symbol.colours
const F = (n) => +n.toFixed(3)

/* A version of the symbol centred in a square of `side`, its larger dimension filling (1 - 2·margin). */
function placed(version, side, margin) {
  const v = symbol.versions[version]
  const s = (side * (1 - 2 * margin)) / Math.max(v.width, v.height)
  const tx = (side - v.width * s) / 2, ty = (side - v.height * s) / 2
  return { v, transform: `translate(${F(tx)} ${F(ty)}) scale(${F(s)})` }
}

/* ---- favicon.svg: the small-size version, with dark-mode colours ---- */
{
  const { v, transform } = placed('small', 64, 0)
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <title>TSR Research Group</title>
  <!-- Generated by scripts/brand-assets.mjs from src/components/brand/symbol.json.
       The small-size version of the symbol (wider gap, rounder corners, no θ
       sector), in the dark-background colours when the browser is dark. -->
  <style>.a{fill:${light.a}}.b{fill:${light.b}}@media (prefers-color-scheme:dark){.a{fill:${dark.a}}.b{fill:${dark.b}}}</style>
  <g transform="${transform}"><path class="a" d="${v.partA}"/><path class="b" d="${v.partB}"/></g>
</svg>
`
  await writeFile(resolve(ROOT, 'public/favicon.svg'), svg)

  /* favicon.ico: the light colours (an ICO has no colour scheme) */
  const flat = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><g transform="${transform}"><path fill="${light.a}" d="${v.partA}"/><path fill="${light.b}" d="${v.partB}"/></g></svg>`
  const SIZES = [16, 32, 48]
  const images = await Promise.all(
    SIZES.map((size) => sharp(Buffer.from(flat), { density: 72 * (size / 64) * 4 }).resize(size, size).png({ compressionLevel: 9 }).toBuffer()),
  )
  /* ICONDIR (6 bytes), one ICONDIRENTRY (16 bytes) per image, then the PNG images. */
  const header = Buffer.alloc(6)
  header.writeUInt16LE(0, 0) // reserved
  header.writeUInt16LE(1, 2) // type: icon
  header.writeUInt16LE(images.length, 4)
  let offset = 6 + 16 * images.length
  const entries = images.map((png, i) => {
    const entry = Buffer.alloc(16)
    entry.writeUInt8(SIZES[i] % 256, 0) // width (0 would mean 256)
    entry.writeUInt8(SIZES[i] % 256, 1) // height
    entry.writeUInt16LE(1, 4) // colour planes
    entry.writeUInt16LE(32, 6) // bits per pixel
    entry.writeUInt32LE(png.length, 8)
    entry.writeUInt32LE(offset, 12)
    offset += png.length
    return entry
  })
  await writeFile(resolve(ROOT, 'public/favicon.ico'), Buffer.concat([header, ...entries, ...images]))
}

/* ---- the full symbol on a white square: touch icon and Organization logo ---- */
async function tile(side, margin, out) {
  const { v, transform } = placed('full', side, margin)
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${side} ${side}" width="${side}" height="${side}">
<rect width="${side}" height="${side}" fill="#ffffff"/>
<g transform="${transform}"><path fill="${light.a}" d="${v.partA}"/><path fill="${light.b}" d="${v.partB}"/><path fill="${light.sector}" d="${v.sector}"/></g></svg>`
  await sharp(Buffer.from(svg)).flatten({ background: '#ffffff' }).png({ compressionLevel: 9 }).toFile(resolve(ROOT, out))
}
await tile(180, 0.16, 'public/apple-touch-icon.png')
await tile(512, 0.12, 'public/images/brand/tsr-logo.png')

/* ---- social card ---- */
{
  const buf = await read('assets/brand/fonts/IBMPlexSans-Regular.ttf')
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
  /* opentype.js's own toPathData can emit "NaN"; serialise the commands here. */
  const N = (n) => {
    if (!Number.isFinite(n)) throw new Error('non-finite glyph coordinate')
    return String(+n.toFixed(3))
  }
  const outline = (text, size, x, y) =>
    font.getPath(text, x, y, size, { kerning: true }).commands.map((c) =>
      c.type === 'Z' ? 'Z' : c.type === 'Q' ? `Q${N(c.x1)} ${N(c.y1)} ${N(c.x)} ${N(c.y)}` : c.type === 'C' ? `C${N(c.x1)} ${N(c.y1)} ${N(c.x2)} ${N(c.y2)} ${N(c.x)} ${N(c.y)}` : `${c.type}${N(c.x)} ${N(c.y)}`,
    ).join('')
  const centred = (text, size, y, fill) => {
    const w = font.getAdvanceWidth(text, size, { kerning: true })
    return `<path fill="${fill}" d="${outline(text, size, (1200 - w) / 2, y)}"/>`
  }
  const logo = (await read('assets/brand/tsr-logo-horizontal.svg')).toString()
  const [, lw, lh] = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(logo).map(Number)
  const H = 150 // the symbol's height on the card
  const scale = H / lh
  const inner = logo.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>[\s\S]*?<\/title>|<desc>[\s\S]*?<\/desc>/g, '')
  const card = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
<rect width="1200" height="630" fill="#ffffff"/>
<rect y="606" width="1200" height="24" fill="${light.b}"/>
<g transform="translate(${F((1200 - lw * scale) / 2)} 170) scale(${F(scale)})">${inner}</g>
${centred(site.tagline, 34, 410, '#1F2933')}
${centred('tsrmethod.github.io', 26, 486, '#52606D')}
</svg>`
  await sharp(Buffer.from(card)).flatten({ background: '#ffffff' }).png({ compressionLevel: 9 }).toFile(resolve(ROOT, 'public/share/social-card.png'))
}

console.log('wrote public/favicon.svg, favicon.ico, apple-touch-icon.png, images/brand/tsr-logo.png, share/social-card.png')
