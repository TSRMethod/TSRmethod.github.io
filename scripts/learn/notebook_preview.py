NOTICE = """<div class="notice recorded" role="note">
<p><strong>A recorded run.</strong> This page shows the notebook exactly as it ran on {date} with BioTSR 1.0.0,
from a clean environment, with every output it produced. It is a page to read: nothing here runs in your
browser.</p>
<p><a class="download" href="{download}" download="biotsr-first-10-minutes.ipynb">Download the notebook (.ipynb)</a>
to run it yourself, or go back to <a href="/software/learn">Learn BioTSR</a> for how to open it.</p>
</div>"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("notebook", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--run-date", required=True, help="the date of the recorded run, YYYY-MM-DD")
    args = parser.parse_args()

    run_date = datetime.date.fromisoformat(args.run_date)
    body, _ = HTMLExporter(template_name="basic").from_filename(str(args.notebook))

    # Exactly one h1, the notebook's title; the notice goes straight after it.
    if body.count("<h1") != 1:
        raise SystemExit("the notebook must have exactly one level-1 heading")
    notice = NOTICE.format(date=f"{run_date.day} {run_date:%B %Y}", download=DOWNLOAD)
    body = re.sub(r"(</h1>)", r"\1" + notice, body, count=1)

    # The helper cell's code, folded away behind a summary.
    helper = re.search(r'(<div class="cell[^"]*celltag_helper"[^>]*>\s*<div class="input">)(.*?)(</div>\s*</div>\s*</div>\s*</div>)',
                       body, flags=re.S)
    if not helper:
        raise SystemExit("no cell tagged 'helper' found")
    # group 3 closes the highlight, input area, inner cell and input divs; the
    # fold ends just before the last of them, so it holds the whole input.
    inner, last = helper.group(3).rsplit("</div>", 1)
    body = (body[: helper.start(2)]
            + '<details class="helper"><summary>Show the helper code</summary>' + helper.group(2)
            + inner + "</details></div>" + last
            + body[helper.end(3):])

    if re.search(r"/Users/|/home/|/private/|/tmp/", body):
        raise SystemExit("the notebook's outputs contain a local path; execute it from a clean folder")

    page = PAGE.format(title=TITLE, description=DESCRIPTION, origin=ORIGIN, path=PAGE_PATH,
                       pygments=HtmlFormatter(style="monokai").get_style_defs(".notebook .highlight"),
                       body=body)
    args.output.write_text(page)
    print(f"wrote {args.output} ({len(page.encode()):,} bytes)")


if __name__ == "__main__":
    main()
