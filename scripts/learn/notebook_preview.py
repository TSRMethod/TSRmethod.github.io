"""Write the body of the Learn BioTSR notebook's page from its executed copy.

RUN BY HAND, NOT BY THE BUILD:

    python3 -m venv .venv && . .venv/bin/activate
    python -m pip install jupyterlab
    python scripts/learn/notebook_preview.py \
        public/learn-files/biotsr-first-10-minutes.ipynb \
        src/content/learn/first-10-minutes.html

The notebook must already have been executed, from a clean environment, with
released BioTSR 1.0.0: this script converts what is stored in it and runs
nothing, so every output on the page is the output of that run.

It writes an HTML fragment, not a page: src/pages/Learn/FirstTenMinutes.jsx
renders it inside the site's layout, under its own title and the notice that
this is a recorded run. So the notebook's level-1 heading is dropped here
(the page has its own), and the helper cell's code is folded away behind a
summary, so the lesson starts with the lesson. The fragment is nbconvert's
minimal ("basic") template; its classes are styled in
src/pages/Learn/FirstTenMinutes.module.css.
"""
import argparse
import re
from pathlib import Path

from nbconvert import HTMLExporter

HEADER = """<!--
  Generated by scripts/learn/notebook_preview.py from
  public/learn-files/biotsr-first-10-minutes.ipynb. Do not edit by hand:
  change the notebook, execute it again from a clean environment, and rerun
  the script.
-->
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("notebook", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    body, _ = HTMLExporter(template_name="basic").from_filename(str(args.notebook))

    # The page has its own <h1>; drop the notebook's.
    if body.count("<h1") != 1:
        raise SystemExit("the notebook must have exactly one level-1 heading")
    body = re.sub(r"<h1[^>]*>.*?</h1>\s*", "", body, count=1, flags=re.S)

    # The helper cell's code, folded away behind a summary. Group 3 closes the
    # highlight, input area, inner cell and input divs; the fold ends just
    # before the last of them, so it holds the whole input.
    helper = re.search(
        r'(<div class="cell[^"]*celltag_helper"[^>]*>\s*<div class="input">)(.*?)(</div>\s*</div>\s*</div>\s*</div>)',
        body,
        flags=re.S,
    )
    if not helper:
        raise SystemExit("no cell tagged 'helper' found")
    inner, last = helper.group(3).rsplit("</div>", 1)
    body = (body[: helper.start(2)]
            + '<details class="helper"><summary>Show the helper code</summary>' + helper.group(2)
            + inner + "</details></div>" + last
            + body[helper.end(3):])

    if re.search(r"/Users/|/home/|/private/|/tmp/", body):
        raise SystemExit("the notebook's outputs contain a local path; execute it from a clean folder")
    if "<script" in body:
        raise SystemExit("the notebook's HTML contains a script")

    args.output.write_text(HEADER + body.strip() + "\n")
    print(f"wrote {args.output} ({args.output.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
